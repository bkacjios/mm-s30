#!/usr/bin/env python3
"""
audio_sizes.py -- build/<version>/assets/audio/{soundfont,sequence}_sizes.h
from the ROM's own audio tables, and sequence_font_table.inc.c (the
sequence-to-soundfont table, for src/linux/reimpl.c).

The N64 build writes these with tools/audio/afile_sizes from the MIPS-built
soundfont and sequence objects; the port has no MIPS toolchain, and the
table entries in the ROM carry the same sizes. Size-0 sequence entries are
pointers to other sequences (no .seq, no object in the N64 build) and are
left out, as is their count.

Run with the decomp's venv from the repository root:
    .venv/bin/python3 pc_tools/audio_sizes.py --version n64-us
"""
import argparse
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "tools"))

from version import version_config  # noqa: E402
from audio.extraction.audio_tables import AudioCodeTable  # noqa: E402


def write_sizes(path, prefix, guard, num_name, table):
    entries = [(i, e.size) for i, e in enumerate(table) if e.size > 0]
    lines = [f"#ifndef {guard}", f"#define {guard}", ""]
    lines += [f"#define {prefix}_{i}_SIZE 0x{size:X}" for i, size in entries]
    lines += ["", f"#define {num_name} {len(entries)}", "", "#endif", ""]
    with open(path, "w") as f:
        f.write("\n".join(lines))
    print(f"{path}: {len(entries)} entries")


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument("--version", default="n64-us")
    args = parser.parse_args()

    config = version_config.load_version_config(args.version)
    code_vram = config.dmadata_segments["code"].vram
    with open(f"extracted/{args.version}/baserom/code", "rb") as f:
        code = memoryview(f.read())

    out_dir = f"build/{args.version}/assets/audio"
    os.makedirs(out_dir, exist_ok=True)
    fonts = AudioCodeTable(code, config.variables["gSoundFontTable"] - code_vram)
    seqs = AudioCodeTable(code, config.variables["gSequenceTable"] - code_vram)
    write_sizes(f"{out_dir}/soundfont_sizes.h", "Soundfont", "SOUNDFONT_SIZES_H_", "NUM_SOUNDFONTS", fonts)
    write_sizes(f"{out_dir}/sequence_sizes.h", "Sequence", "SEQUENCE_SIZES_H_", "NUM_SEQUENCES", seqs)

    # The sequence font table: a u16 offset per sequence, then the font
    # count and font ids each offset points at. It lies between
    # gSequenceFontTable and gSequenceTable in code; the N64 build makes it
    # from the sequences. The offsets are swapped to the port's byte order.
    start = config.variables["gSequenceFontTable"] - code_vram
    end = config.variables["gSequenceTable"] - code_vram
    table = bytearray(code[start:end])
    for i in range(len(seqs)):
        table[i * 2], table[i * 2 + 1] = table[i * 2 + 1], table[i * 2]
    path = f"{out_dir}/sequence_font_table.inc.c"
    with open(path, "w") as f:
        f.write("// Generated by pc_tools/audio_sizes.py from the ROM (u16 offsets in host order)\n")
        for i in range(0, len(table), 16):
            f.write(" ".join(f"0x{b:02X}," for b in table[i:i + 16]) + "\n")
    print(f"{path}: {len(table)} bytes, {len(seqs)} sequences")


if __name__ == "__main__":
    main()
